package org.nethergames.gsms.data.model;

public class GameServerCounter {
    private int count;
    private int max;

    public int getCount() {
        return count;
    }

    public void setCount(int count) {
        this.count = count;
    }

    public int getMax() {
        return max;
    }

    public void setMax(int max) {
        this.max = max;
    }
}
